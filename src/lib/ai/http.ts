/**
 * Pure HTTP contract for the AI entry point: parse an untrusted body, and map a
 * gateway result to a status code and a user-safe payload.
 *
 * Kept free of Next.js imports so it can be tested directly. The two security
 * decisions live here, not in the route:
 * 1. the client can never choose the data classification, the budget or the
 *    provider — those are server-side values and any attempt to set them is a
 *    rejected request, not a silently ignored field;
 * 2. no provider detail, key or internal error text reaches the response;
 * 3. the body is read with a hard byte ceiling before any JSON parsing, so an
 *    enormous or unbounded stream cannot be buffered in memory;
 * 4. the admin must attest, per request, that the text is PUBLIC. The forced
 *    classification alone cannot prove that: copied financial or personal data
 *    would still be PUBLIC on paper. The confirmation shifts responsibility to
 *    the operator and is recorded; it is not a sensitive-data detector.
 */
import { PUBLIC_ATTESTATION, ROUTE_LIMITS } from "./policy";
import type { FailureCode, GatewayAttempt, GatewayResult, TaskRequest } from "./types";

/** Fields a browser must never control. Presence is an error, not a no-op. */
const SERVER_OWNED_FIELDS = [
  "dataClass",
  "dataClassification",
  "requestedBudgetEur",
  "budget",
  "budgetEur",
  "mode",
  "provider",
  "providerAllowlist",
  "model",
  "modelId",
  "messages",
  "system",
  "tools",
  "maxRequests",
  "timeoutMs",
] as const;

export type ParsedAiRequest =
  | { ok: true; task: TaskRequest; prompt: string; attestationVersion: string }
  | { ok: false; status: number; error: string };

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

/**
 * Validate the body and build the task. `taskId` is generated by the server so a
 * caller cannot collide with, or impersonate, another audit entry.
 */
export function parseAiRequest(body: unknown, taskId: string): ParsedAiRequest {
  if (!isRecord(body)) return { ok: false, status: 400, error: "Richiesta non valida." };
  if (typeof taskId !== "string" || taskId.trim() === "") {
    return { ok: false, status: 500, error: "Identificativo del task non disponibile." };
  }

  const forbidden = SERVER_OWNED_FIELDS.filter((field) =>
    Object.prototype.hasOwnProperty.call(body, field),
  );
  if (forbidden.length > 0) {
    return {
      ok: false,
      status: 400,
      error: `Il client non può impostare: ${forbidden.join(", ")}. Classificazione, budget e provider sono decisi dal server.`,
    };
  }

  // Explicit, boolean, per request: a missing or falsy value is a rejection, not
  // a default. No text is ever sent without the operator taking responsibility.
  if (body[PUBLIC_ATTESTATION.field] !== true) {
    return {
      ok: false,
      status: 400,
      error:
        "Attestazione PUBLIC mancante: conferma che il testo è pubblico e non contiene dati INTERNAL, CONFIDENTIAL o SECRET, credenziali, chiavi o dati personali.",
    };
  }

  const objectiveRaw = body.objective;
  if (typeof objectiveRaw !== "string" || objectiveRaw.trim() === "") {
    return { ok: false, status: 400, error: "Obiettivo mancante." };
  }
  const objective = objectiveRaw.trim();
  if (objective.length > ROUTE_LIMITS.maxObjectiveChars) {
    return {
      ok: false,
      status: 400,
      error: `Obiettivo oltre ${ROUTE_LIMITS.maxObjectiveChars} caratteri.`,
    };
  }

  const promptRaw = body.prompt;
  if (typeof promptRaw !== "string" || promptRaw.trim() === "") {
    return { ok: false, status: 400, error: "Prompt mancante." };
  }
  const prompt = promptRaw.trim();
  if (prompt.length > ROUTE_LIMITS.maxPromptChars) {
    return {
      ok: false,
      status: 413,
      error: `Prompt oltre il limite di ${ROUTE_LIMITS.maxPromptChars} caratteri.`,
    };
  }

  return {
    ok: true,
    prompt,
    task: {
      taskId,
      objective,
      // Hosted free models are approved for PUBLIC data only. The value is set
      // here, never read from the request.
      dataClass: "PUBLIC",
      maxRequests: ROUTE_LIMITS.requestsPerTask,
    },
    attestationVersion: PUBLIC_ATTESTATION.version,
  };
}

export type BodyRead =
  | { ok: true; value: unknown }
  | { ok: false; status: number; error: string };

/**
 * Read a JSON body with a hard ceiling. The declared Content-Length is checked
 * first (a request that already declares too many bytes is refused without
 * reading it), but it is never trusted on its own: the stream is read chunk by
 * chunk and aborted as soon as it crosses the limit. A missing length is
 * allowed — chunked uploads are legitimate — and still bounded. Malformed JSON
 * and invalid UTF-8 are 400.
 */
export async function readJsonBody(
  req: Request,
  maxBytes: number = ROUTE_LIMITS.maxBodyBytes,
): Promise<BodyRead> {
  const declared = req.headers.get("content-length");
  if (declared !== null) {
    const trimmed = declared.trim();
    if (!/^\d+$/.test(trimmed)) {
      return { ok: false, status: 400, error: "Content-Length non valido." };
    }
    const length = Number(trimmed);
    if (!Number.isSafeInteger(length)) {
      return { ok: false, status: 400, error: "Content-Length non valido." };
    }
    if (length === 0) return { ok: false, status: 400, error: "Richiesta non valida." };
    if (length > maxBytes) {
      return { ok: false, status: 413, error: `Richiesta oltre il limite di ${maxBytes} byte.` };
    }
  }

  const stream = req.body;
  if (!stream) return { ok: false, status: 400, error: "Richiesta non valida." };

  const reader = stream.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      if (!value) continue;
      total += value.byteLength;
      if (total > maxBytes) {
        await reader.cancel().catch(() => undefined);
        return { ok: false, status: 413, error: `Richiesta oltre il limite di ${maxBytes} byte.` };
      }
      chunks.push(value);
    }
  } catch {
    return { ok: false, status: 400, error: "Corpo della richiesta non leggibile." };
  } finally {
    reader.releaseLock();
  }

  const bytes = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    bytes.set(chunk, offset);
    offset += chunk.byteLength;
  }

  let text: string;
  try {
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    return { ok: false, status: 400, error: "Richiesta non valida." };
  }

  try {
    return { ok: true, value: JSON.parse(text) as unknown };
  } catch {
    return { ok: false, status: 400, error: "Richiesta non valida." };
  }
}

const FAILURE_RESPONSE: Record<FailureCode, { status: number; message: string }> = {
  PRIVACY_BLOCKED: { status: 403, message: "La richiesta è stata bloccata dalla policy di privacy." },
  TASK_BUDGET_EXCEEDED: { status: 400, message: "La richiesta supera i limiti del task." },
  MODEL_NOT_APPROVED: { status: 422, message: "Nessun modello gratuito approvato disponibile." },
  QUOTA_EXHAUSTED: { status: 429, message: "Quota gratuita esaurita per la finestra corrente." },
  RATE_LIMITED: { status: 429, message: "Limite di richieste raggiunto: riprova più tardi." },
  BILLING_REQUIRED: {
    status: 402,
    message: "Il provider richiede credito: nessun invio e nessun fallback a pagamento.",
  },
  TIMEOUT: { status: 504, message: "Il provider non ha risposto entro il tempo massimo." },
  INVALID_RESPONSE: { status: 502, message: "Il provider ha restituito una risposta non valida." },
  PROVIDER_UNAVAILABLE: { status: 503, message: "Provider non disponibile in questo momento." },
};

/** Attempts are audit facts: provider/model/outcome only, never `detail`. */
function safeAttempts(attempts: GatewayAttempt[]): GatewayAttempt[] {
  return attempts.map((attempt) => {
    const safe: GatewayAttempt = {
      providerId: attempt.providerId,
      modelId: attempt.modelId,
      version: attempt.version,
      outcome: attempt.outcome,
      durationMs: attempt.durationMs,
    };
    if (attempt.usage) safe.usage = attempt.usage;
    return safe;
  });
}

export type AiHttpResponse = { status: number; body: Record<string, unknown> };

/** Map a gateway outcome to an HTTP status without leaking internal detail. */
export function toAiResponse(result: GatewayResult): AiHttpResponse {
  if (result.ok) {
    return {
      status: 200,
      body: {
        ok: true,
        providerId: result.providerId,
        modelId: result.modelId,
        version: result.version,
        text: result.text,
        attempts: safeAttempts(result.attempts),
      },
    };
  }

  const mapped = FAILURE_RESPONSE[result.code] ?? {
    status: 503,
    message: "Richiesta non eseguita.",
  };
  return {
    status: mapped.status,
    body: {
      ok: false,
      code: result.code,
      queued: result.queued,
      error: mapped.message,
      attempts: safeAttempts(result.attempts),
    },
  };
}
